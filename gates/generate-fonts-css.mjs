// Writes css/fonts.css from fonts/families.json [T19, AR39].
//
// One @font-face per face and script: the family name the tokens use,
// the weight (a range for a variable face), the style, `font-display:
// swap`, the relative url() the manifest walk follows, and a
// unicode-range so a page that never shows a kanji never downloads the
// Japanese subset. Generated, committed, refused stale by `--check` —
// the same shape as every other artefact here (AR26).
//
// The stylesheet is the subject of gates/check-fonts.mjs: what it
// promises is what fonts/ must carry. A family with a Reserved Font Name
// ships nothing and appears nowhere in here.
//
// Usage:
//   node gates/generate-fonts-css.mjs           write css/fonts.css
//   node gates/generate-fonts-css.mjs --check   exit 1 if it would change

import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';

const root = new URL('../', import.meta.url);
const OUT = new URL('css/fonts.css', root);

/** The unicode-range per script, as the browser reads it (the subsets' own ranges). */
export const RANGES = {
    latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
    'latin-ext':
        'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
    arabic: 'U+0600-06FF, U+0750-077F, U+0870-088E, U+0890-0891, U+0898-08E1, U+08E3-08FF, U+200C-200E, U+2010-2011, U+204F, U+2E41, U+FB50-FDFF, U+FE70-FE74, U+FE76-FEFC',
    japanese: 'U+3000-303F, U+3040-309F, U+30A0-30FF, U+FF00-FFEF, U+4E00-9FFF',
};

/**
 * @param {Record<string, any>} families fonts/families.json, comment key removed
 * @returns {string}
 */
export function fontsCss(families) {
    const lines = [
        '/* @kp-soft/themes — css/fonts.css',
        '   GENERATED by gates/generate-fonts-css.mjs from fonts/families.json [T19, AR39].',
        '   Do not edit: `npm run gates` fails when this file and the plan disagree.',
        '',
        '   The shipped faces, one @font-face per face and script. Load it beside',
        '   themes.css; the theme tokens name these families first and a system',
        '   face after them, so a page without this file (chassis-rs before it',
        '   vendors the fonts, or a consumer that chose not to) still reads.',
        '   A family whose licence declares a Reserved Font Name is here under',
        '   the renamed family the build gave it (R6-Q1): the tokens name that',
        '   family first and the original after it, for a reader who has it. */',
        '',
    ];
    let faces = 0;
    for (const [slug, family] of Object.entries(families)) {
        if (family.reservedFontName && !family.subset) continue;
        lines.push(
            `/* ${family.renamed ? `${family.renamed} (renamed from ${family.family}, Reserved Font Name '${family.reservedWord}')` : family.family} — ${family.licence}, fonts/${slug}/LICENSE; named by ${family.themes.join(', ')} */`,
        );
        for (const face of family.faces) {
            for (const script of face.scripts) {
                const file = `${face.file}${face.scripts.length > 1 ? `-${script}` : ''}.woff2`;
                lines.push('@font-face {');
                lines.push(`    font-family: '${family.renamed ?? family.family}';`);
                lines.push(`    font-style: ${face.style};`);
                lines.push(`    font-weight: ${face.weight};`);
                lines.push('    font-display: swap;');
                lines.push(`    src: url('../fonts/${slug}/${file}') format('woff2');`);
                lines.push(`    unicode-range: ${RANGES[/** @type {keyof typeof RANGES} */ (script)]};`);
                lines.push('}');
                faces++;
            }
        }
        lines.push('');
    }
    return lines.join('\n').replace(/\n+$/, '\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const families = JSON.parse(readFileSync(new URL('fonts/families.json', root), 'utf8'));
    delete families['//'];
    const content = fontsCss(families);
    if (process.argv.includes('--check')) {
        let current = '';
        try {
            current = readFileSync(OUT, 'utf8');
        } catch {
            current = '';
        }
        if (current !== content) {
            console.error('css/fonts.css does not match fonts/families.json. Run `npm run generate:fonts-css` and commit the result.');
            process.exit(1);
        }
        const faces = (content.match(/@font-face/g) ?? []).length;
        console.log(`Fonts stylesheet: css/fonts.css matches fonts/families.json (${faces} faces).`);
        process.exit(0);
    }
    writeFileSync(OUT, content);
    console.log(`wrote css/fonts.css (${(content.match(/@font-face/g) ?? []).length} faces).`);
}
