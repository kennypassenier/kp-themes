// The table of configurable shortcuts in docs/USER_GUIDE.md, written from the constants themselves [keys-1103].
//
// Every `X_KEY_ATTRIBUTE = 'data-kp-…'` in js/ with its `X_KEY = '…'` default is one row: the attribute, the default key
// and the sentence over the attribute. The table sits between two marker comments in the guide;
// `node gates/key-table.mjs --write` rewrites it, `node gates/key-table.mjs --check` (the key-literals gate) refuses a stale one.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const ROOT = new URL('../', import.meta.url).pathname;
const GUIDE = join(ROOT, 'docs/USER_GUIDE.md');
export const BEGIN = '<!-- keys:begin (generated by gates/key-table.mjs; do not edit) -->';
export const END = '<!-- keys:end -->';

/** @param {string} dir @returns {string[]} */
const sources = (dir) =>
    readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
        e.isDirectory() ? sources(join(dir, e.name)) : e.name.endsWith('.js') ? [join(dir, e.name)] : [],
    );

/** Every shortcut a page can change: `{ attribute, key, what }`, in file order. */
export function shortcuts() {
    const rows = [];
    for (const file of sources(join(ROOT, 'js')).sort()) {
        const text = readFileSync(file, 'utf8');
        for (const m of text.matchAll(/\/\*\*\s*([^*]*?)\s*\*\/\s*export const (\w+_KEY)_ATTRIBUTE = '([^']+)'/g)) {
            const base = m[2];
            const def = new RegExp(String.raw`export const ${base} = '([^']+)'`).exec(text);
            if (!def) throw new Error(`${file}: ${base}_ATTRIBUTE has no ${base} default.`);
            rows.push({ attribute: m[3], key: def[1], what: m[1].replace(/\s+/g, ' ').replace(/\s*\(a key spec[^)]*\)/, '').replace(/\.$/, '') });
        }
    }
    return rows.sort((a, b) => a.attribute.localeCompare(b.attribute));
}

/** The block between the markers, as it should read. */
export function block() {
    const lines = shortcuts().map((r) => `| \`${r.attribute}\` | \`${r.key}\` | ${r.what} |`);
    return [BEGIN, '', '| Attribute | Default | What it does |', '| --- | --- | --- |', ...lines, '', END].join('\n');
}

/** @param {string} guide @returns {[number, number] | null} */
const span = (guide) => {
    const a = guide.indexOf(BEGIN);
    const b = guide.indexOf(END);
    return a < 0 || b < 0 ? null : [a, b + END.length];
};

/** Whether the guide's table is current; the message says what to run when not. @returns {string | null} */
export function stale() {
    const guide = readFileSync(GUIDE, 'utf8');
    const at = span(guide);
    if (!at) return 'docs/USER_GUIDE.md has no shortcut table markers; run node gates/key-table.mjs --write';
    return guide.slice(...at) === block() ? null : 'The shortcut table in docs/USER_GUIDE.md is out of date; run node gates/key-table.mjs --write';
}

if (import.meta.url === `file://${process.argv[1]}`) {
    if (process.argv.includes('--write')) {
        const guide = readFileSync(GUIDE, 'utf8');
        const at = span(guide);
        if (!at) throw new Error('Put the two marker comments in docs/USER_GUIDE.md first.');
        writeFileSync(GUIDE, guide.slice(0, at[0]) + block() + guide.slice(at[1]));
        console.log(`shortcut table: ${shortcuts().length} rows written.`);
    } else {
        const problem = stale();
        if (problem) {
            console.error(`[key-table] ${problem}`);
            process.exit(1);
        }
        console.log(`shortcut table: ${shortcuts().length} rows, current.`);
    }
}
