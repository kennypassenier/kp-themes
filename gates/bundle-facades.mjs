// One facade per public dist/js entry, served from the single bundle [superset-1103; chassis-rs 03/11].
//
// dist/js/<entry>.js is the split bundle: a page that imports four entries fetches about 330 files. A consumer who
// would rather fetch ONE file maps every kp import to dist/kp-themes.min.js, but that file's names are flat names, and a
// module's own names are not all flat (OPEN_EVENT is declared by three modules and is only PALETTE_OPEN_EVENT there).
// dist/bundle/<entry>.js re-exports from ../kp-themes.min.js under exactly the names dist/js/<entry>.js has, so an
// import map `"/static/kp/js/": "/static/kp/bundle/"` swaps the 330 files for one with no change to any import.
//
// Three forms, best first, all from the names esbuild reports for the module (gates/bundle-metafile.mjs):
//   1. the name is flat in the bundle: `export { name } from`, a live binding;
//   2. the name is declared by several modules, so the bundle has `<module prefix><Name>`: `export { alias as name } from`,
//      also a live binding;
//   3. otherwise the module's namespace in the bundle (`<module>Exports`): `export const { name } = ns`. A const copies the
//      value at load time, so a `let` re-assigned later would not follow; classes, functions and constants are unaffected.
//      No public entry needs this form today (the generated header says which names do).

import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import { byCodeUnit } from './code-unit-order.mjs';

/** The folder under dist/ the facades are written to. */
export const FACADE_DIR = 'bundle';

/** The bundle every facade reads, relative to dist/bundle/. */
export const BUNDLE_URL = '../kp-themes.min.js';

/**
 * The facades' source text.
 * @param {{ out: string, module: string }[]} entries the public entries (gates/bundle-entries.mjs)
 * @param {Map<string, string[]>} exportsOf `./js/<x>.js` → the names it exports
 * @param {Map<string, string[]>} declared name → the modules that declare it
 * @param {{ module: string, name: string, alias: string }[]} aliasList the bundle's aliases
 * @param {(module: string) => string} namespaceFor
 * @param {string} version
 * @returns {{ name: string, content: string }[]} names relative to dist/
 */
export function facadeFiles(entries, exportsOf, declared, aliasList, namespaceFor, version) {
    const alias = new Map(aliasList.map((a) => [`${a.module}\0${a.name}`, a.alias]));
    return entries.map((entry) => {
        const module = `./${entry.module}`;
        const names = exportsOf.get(module);
        if (!names) throw new Error(`no export list for ${module}`);
        /** @type {string[]} */ const live = [];
        /** @type {string[]} */ const copied = [];
        for (const name of names) {
            if (name === 'default') continue;
            const flat = declared.get(name)?.length === 1;
            const prefixed = alias.get(`${module}\0${name}`);
            if (flat) live.push(name);
            else if (prefixed) live.push(`${prefixed} as ${name}`);
            else copied.push(name);
        }
        const ns = namespaceFor(module);
        const lines = [`/* @kp-soft/themes v${version}, dist/${FACADE_DIR}/${entry.out}.js: the names of dist/js/${entry.out}.js from the single bundle. Generated by gates/bundle-facades.mjs; do not edit. */`];
        const hasDefault = names.includes('default');
        if (live.length) lines.push(`export { ${live.join(', ')} } from '${BUNDLE_URL}';`);
        if (copied.length || hasDefault) lines.push(`import { ${ns} as m } from '${BUNDLE_URL}';`);
        if (copied.length) lines.push(`export const { ${copied.join(', ')} } = m;`);
        if (hasDefault) lines.push('export default m.default;');
        return { name: `${FACADE_DIR}/${entry.out}.js`, content: lines.join('\n') + '\n' };
    });
}

/**
 * The manifest list of the facades, a module gates/checksums.mjs spreads into FILES.
 * @param {{ name: string }[]} files
 * @returns {string}
 */
export function facadeManifest(files) {
    const paths = files.map((f) => `    'dist/${f.name}',`).sort((a, b) => byCodeUnit(a, b));
    return (
        '// The facades in dist/bundle/ (gates/bundle-facades.mjs) for SHA256SUMS.\n' +
        '// Generated by gates/generate-bundle.mjs — do not edit by hand; gates/check-manifest.mjs expects them through the `./dist/bundle/*` export.\n' +
        `export const FACADE_FILES = [\n${paths.join('\n')}\n];\n`
    );
}

/**
 * Every name a module's source exports: `export { a as b, c }` lists, `export const { a, b } =` destructurings, `export default`.
 * Written for esbuild's output and the facades above, which use only these forms.
 * @param {string} source
 * @returns {Set<string>}
 */
export function exportNames(source) {
    const names = new Set();
    for (const list of source.matchAll(/export\s*\{([^}]*)\}/g)) {
        for (const item of list[1].split(',')) {
            const name = item.trim().split(/\s+as\s+/).pop()?.trim();
            if (name) names.add(name);
        }
    }
    for (const list of source.matchAll(/export\s+const\s*\{([^}]*)\}\s*=/g)) {
        for (const item of list[1].split(',')) if (item.trim()) names.add(item.trim());
    }
    if (/\bexport\s+default\b|\bas\s+default\b/.test(source)) names.add('default');
    return names;
}

/**
 * The names a facade takes from the bundle, by their name in the bundle: the left side of each `export { x as y } from`.
 * @param {string} source
 * @returns {string[]}
 */
export function bundleNamesUsed(source) {
    const out = [];
    for (const list of source.matchAll(/export\s*\{([^}]*)\}\s*from/g)) {
        for (const item of list[1].split(',')) {
            const name = item.trim().split(/\s+as\s+/)[0]?.trim();
            if (name) out.push(name);
        }
    }
    return out;
}

/**
 * The files in dist/bundle/ that the build no longer writes: facades of an entry that is gone.
 * @param {string} root
 * @param {{ name: string }[]} files the facades the build writes, names relative to dist/
 * @returns {string[]} names relative to dist/
 */
export function staleFacades(root, files) {
    const wanted = new Set(files.map((f) => f.name));
    let present = [];
    try {
        present = readdirSync(join(root, 'dist', FACADE_DIR));
    } catch {
        return [];
    }
    return present.map((name) => `${FACADE_DIR}/${name}`).filter((name) => !wanted.has(name));
}
