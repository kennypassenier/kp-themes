// The base stylesheet: the full bundle without its twelve registers, plus the fonts [load-1102].
//
// dist/kp-themes.css carries every register, so a page that wears one theme
// still downloads twelve. Measured on slow 4G for habits (docs/ux/load.md,
// phase 3) that is the largest single cost of a first load. The base is the
// other half of the lazy-register route: one file with everything that is the
// same in every theme, and the theme's own register fetched beside it by
// js/lazy-register.js from dist/css/<theme>-register.min.css.
//
// What goes in is read from the same `bundled` role the bundle reads
// (gates/config.json), in the same order, minus every `*-register.css`, so
// the base can never carry a stylesheet the bundle does not. css/fonts.css is
// added last: it is not in the bundle (a consumer links it beside), but a page
// that takes the base wants one link for everything shared, and an @font-face
// block sits outside every cascade layer, so its place in the file decides
// nothing. Its `url(../fonts/…)` resolves from dist/ to the package's fonts/
// exactly as it does from css/, so no path is rewritten.
//
// The layer order is still stated first: css/themes.css opens the file, so a
// register that arrives later lands in kp.register, between components and
// layout, as it does with the loose files.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stylesheets } from './stylesheets.mjs';

/** Every stylesheet in the base, in load order. */
export const BASE_SHEETS = [...stylesheets('bundled').filter((file) => !file.endsWith('-register.css')), 'css/fonts.css'];

/** Where the base is written, repository-relative. */
export const BASE_FILE = 'dist/kp-themes-base.min.css';

/**
 * The base stylesheet, unminified, with a header naming what is in it.
 * @param {string} root the repository root
 * @param {string} version the package version
 * @returns {string}
 */
export function baseSource(root, version) {
    const head = `/* @kp-soft/themes v${version} — ${BASE_FILE}
   Generated by gates/generate-min.mjs (gates/min-base.mjs) — do not edit by hand.

   ${BASE_SHEETS.join(', ')}, concatenated in load order.
   No register: link one beside it, or let js/lazy-register.js fetch the active one. */\n\n`;
    return head + BASE_SHEETS.map((file) => readFileSync(join(root, file), 'utf8').trimEnd()).join('\n\n') + '\n';
}
