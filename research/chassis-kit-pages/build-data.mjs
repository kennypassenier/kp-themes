// Embeds the four JSON files captured from the running example service (examples/inbox of chassis-rs 3.8.0, 2026-10-19)
// into captured.js, so the demo reads them in the same module graph as the page (no fetch, nothing to wait for).
// Run: node research/chassis-kit-pages/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const read = (name) => JSON.parse(readFileSync(join(here, 'data', `captured-${name}.json`), 'utf8'));
const captured = { status: read('status'), clients: read('clients'), requests: read('requests'), healthz: read('healthz') };
writeFileSync(
    join(here, 'captured.js'),
    `// Generated by build-data.mjs from data/captured-*.json: what the running example service answered.\n` +
        `// Do not edit; run the script again.\nexport const CAPTURED = ${JSON.stringify(captured, null, 4)};\n`,
);
console.log('captured.js written');
